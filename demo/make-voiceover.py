# Generates the demo voiceover lines with ElevenLabs text-to-speech into demo/out/vo/.
# Needs ELEVENLABS_API_KEY and a paid ElevenLabs plan (library voices aren't available to the free API).
# The voice is Viraj, "Confident and Natural" (an Indian English male voice from the ElevenLabs voice library;
# add it to your account first). Spellings like "L T X" and "Comfy U I" are there to get the pronunciation right.
#   python3 demo/make-voiceover.py            (VOICE_ID=... to use a different voice, MODEL=... to change model)
import json, os, urllib.request

key = os.environ["ELEVENLABS_API_KEY"]
voice = os.environ.get("VOICE_ID", "fPIfC3elMLbN9tNwMXkw")
model = os.environ.get("MODEL", "eleven_multilingual_v2")
lines = {
    "1_intro": "This is Higgsy. You call her, and she answers questions about Higgsfield, out loud. I built her for the Comfy open-source Higgsfield challenge.",
    "2_rule": "Most assistants make up prices. Higgsy only repeats what Higgsfield's own pages say, with the date. If she can't find it, she says so.",
    "3a_art": "Higgsy herself is generated by Z-Image Turbo, an open-weights model.",
    "3b_cut": "A background-removal workflow cuts her out.",
    "3c_ltx": "L T X two point three animates her greeting, and the little thinking hop.",
    "3d_live": "And when you ask for an example, the call runs a Comfy U I workflow live. The workflow is linked under every image.",
    "4_outro": "Try it at the link, or run it yourself. The code is M I T, and every workflow is in the repo. Hashtag Open Source Higgsfield.",
}
os.makedirs("demo/out/vo", exist_ok=True)
total = 0
for name, text in lines.items():
    body = json.dumps({"text": text, "model_id": model, "language_code": "en", "voice_settings": {"stability": 0.5, "similarity_boost": 0.8, "style": 0.15, "use_speaker_boost": True}}).encode()
    req = urllib.request.Request(f"https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format=mp3_44100_128", data=body, headers={"xi-api-key": key, "content-type": "application/json"})
    try:
        data = urllib.request.urlopen(req, timeout=120).read()
    except urllib.error.HTTPError as e:
        raise SystemExit(f"{name}: HTTP {e.code} {e.read()[:300]!r}")
    open(f"demo/out/vo/{name}.mp3", "wb").write(data)
    total += len(text)
    print(f"{name}: {len(text)} chars, {len(data) // 1024} KB")
print("characters sent:", total)
